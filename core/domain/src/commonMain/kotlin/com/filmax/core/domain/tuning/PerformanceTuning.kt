package com.filmax.core.domain.tuning

/**
 * Единая сводка скоростных лимитов, порогов и таймаутов, которыми приложение намеренно
 * придерживает фоновую/сетевую работу — чтобы она не конкурировала за канал и CPU с тем, что
 * пользователь делает прямо сейчас (листает списки, открывает тайтл, смотрит видео). Раньше эти
 * числа были разбросаны приватными константами по разным файлам и модулям — здесь они
 * собраны в одном месте для подстройки, а КАЖДОЕ место, которое их применяет, читает именно эти
 * поля (а не свою копию), поэтому файл не может тихо разойтись с реальным поведением.
 *
 * ЧТО ЗАМЕДЛЯЕТ ПОЯВЛЕНИЕ ТАЙТЛОВ/КАРТИНОК СИЛЬНЕЕ ВСЕГО (по убыванию влияния):
 *  1. [BackgroundThrottle.COOLDOWN_MS] — 10 c после ЛЮБОГО обычного (не фонового) запроса или
 *     просмотра картинки открытого экрана вся фоновая докачка (детали тайтлов + постеры) держит
 *     себя придушенной; во время воспроизведения видео — придушена всё время плейбэка, а не 10 c.
 *     При активном использовании приложения фон почти никогда не разгоняется до полной скорости.
 *  2. [BackgroundThrottle.BACKGROUND_IMAGE_BYTES_PER_SECOND] — если пользовательская активность
 *     началась уже после старта фоновой закачки, её тело читается не быстрее 256 КБ/с.
 *  3. Обе фоновые очереди (детали тайтла — `TitleBackgroundFetcherImpl`, постеры —
 *     `ImagePrefetcherImpl`) архитектурно СТРОГО последовательны — один элемент за раз, без
 *     параллелизма. Это не константа, а выбор дизайна: очередь не должна отъедать соединения у
 *     активного контента, поэтому здесь нет отдельного числа для «поднять».
 *  4. [ForegroundDetailsConcurrency] — не более 4 одновременных `getItemDetails`, даже когда
 *     пользователь СМОТРИТ на экран (Библиотека «В процессе», главная «Продолжить просмотр») —
 *     самый заметный для пользователя лимит из всех: именно он определяет, как быстро карточки
 *     на видимом экране дозаполняются годом/жанром/рейтингом.
 *
 * Остальные группы ([BackgroundQueues], [NetworkClient], [ImageCache], [Warmup]) влияют на
 * скорость заметно слабее либо только в частных случаях (таймауты, повторы, объём кэша).
 */
object PerformanceTuning {

    /**
     * См. [com.filmax.core.domain.cache.ImagePrefetchThrottle]. Источники, которые продлевают
     * throttle: `HttpClientFactory` (core:network, любой НЕ фоновый запрос основного API-клиента),
     * `FilmaxImageLoaderFactory` (app, любая НЕ фоновая загрузка картинки), `PlayerScreenModel`
     * (пока идёт воспроизведение).
     */
    object BackgroundThrottle {
        /**
         * Сколько миллисекунд после любой не-фоновой сетевой/UI-активности фоновая докачка
         * (картинки + детали тайтлов) держит себя придушенной.
         *
         * Больше — фон СПОКОЙНЕЕ (меньше конкурирует за канал при активном использовании), но
         * фоновые докачки завершаются заметно дольше при активном скролле/просмотре. Меньше —
         * постеры/жанры у ещё не открытых тайтлов появляются быстрее ценой конкуренции за канал
         * с тем, что человек смотрит/листает прямо сейчас.
         */
        const val COOLDOWN_MS = 10_000L

        /**
         * Как часто обе фоновые очереди (детали тайтла и картинки — используют одно и то же
         * число) перепроверяют, снят ли throttle, прежде чем взять из очереди следующий элемент.
         * Сама по себе НЕ влияет на скорость закачки — только на задержку реакции на конец
         * [COOLDOWN_MS] (в среднем половина этого интервала).
         */
        const val THROTTLE_POLL_INTERVAL_MS = 500L

        /**
         * Жёсткий потолок скорости фоновой закачки КАРТИНОК, если throttle активен в момент
         * получения ответа (см. [COOLDOWN_MS]) — реализован в
         * `FilmaxImageLoaderFactory.ThrottledResponseBody`. Не применяется к обычным
         * (не фоновым) загрузкам; без throttle фон качает на полной скорости соединения.
         *
         * Поднять это значение — самый прямой способ ускорить именно фоновую докачку постеров,
         * не трогая приоритет активного контента ([COOLDOWN_MS] и так почти всё время держит
         * фон придушенным при активном пользовании).
         */
        const val BACKGROUND_IMAGE_BYTES_PER_SECOND = 256L * 1024
    }

    /**
     * Лимиты параллелизма `CatalogRepository.getItemDetails` на ВИДИМЫХ экранах (не фон) — без
     * них холодный кэш легко устроил бы залп из 15-20 одновременных запросов на список «В
     * процессе»/историю.
     */
    object ForegroundDetailsConcurrency {
        /**
         * `LibraryScreenModel.loadTitleDetails` — сколько тайтлов «В процессе»/истории
         * одновременно догружают жанр/год/рейтинг на экране «Я смотрю».
         */
        const val LIBRARY_TITLE_DETAILS = 4

        /**
         * `ContinuationResolver.resolve` — то же самое для расчёта continuation по истории
         * (используется на главной, «Продолжить просмотр»). Намеренно то же число и та же
         * причина, что у [LIBRARY_TITLE_DETAILS].
         */
        const val CONTINUATION_DETAILS = 4
    }

    /**
     * Таймауты и потолки очередей фонового докачивания. Сами очереди (`TitleBackgroundFetcherImpl`,
     * `ImagePrefetcherImpl`) строго последовательны — здесь только «сколько ждать одного элемента»
     * и «сколько элементов допустить в очередь», а не про скорость самой закачки (см.
     * [BackgroundThrottle]).
     */
    object BackgroundQueues {
        /** Таймаут одного `getItemDetails` в фоновой очереди деталей тайтла. */
        const val TITLE_DETAILS_FETCH_TIMEOUT_MS = 15_000L

        /**
         * Таймаут одной фоновой закачки картинки. Не 15 c, как у деталей тайтла: закачка сама
         * себя придушивает до [BackgroundThrottle.BACKGROUND_IMAGE_BYTES_PER_SECOND], а
         * бэкдропы/кадры весят 2-3 МБ — на такой скорости это легитимно дольше 15 c.
         */
        const val IMAGE_PREFETCH_TIMEOUT_MS = 90_000L

        /**
         * Максимум одновременно стоящих в очереди id тайтлов (drop-newest при переполнении —
         * новый id просто не попадает в очередь, старые не вытесняются). Очередь получает id
         * КАЖДОГО тайтла КАЖДОГО спискового ответа (главная, поиск, похожее, подборки), поэтому
         * обычный скролл каталога легко выедает небольшой потолок.
         */
        const val MAX_QUEUED_TITLE_IDS = 1000

        /** То же самое, но для очереди фоновой закачки картинок (ключи постеров/фото). */
        const val MAX_QUEUED_IMAGE_KEYS = 1000

        /**
         * Размер декода (px) для прогрева картинки в фоне — результат тут же отбрасывается
         * (в память не кладётся), нужен только чтобы Coil не декодировал прогрев в полное
         * разрешение и не отъедал этим CPU/память впустую.
         */
        const val IMAGE_PREFETCH_DECODE_SIZE_PX = 32
    }

    /** `HttpClientFactory` (core:network) — таймауты и повторы основного API-клиента. */
    object NetworkClient {
        /** Таймаут запроса целиком (соединение + получение ответа), мс. */
        const val REQUEST_TIMEOUT_MS = 12_000L

        /** Таймаут установки TCP-соединения, мс. */
        const val CONNECT_TIMEOUT_MS = 8_000L

        /** Таймаут ожидания данных по уже открытому сокету, мс. */
        const val SOCKET_TIMEOUT_MS = 10_000L

        /**
         * Сколько раз тихо повторяется сбойный GET/HEAD (5xx или сетевая ошибка) с
         * экспоненциальной задержкой между попытками, прежде чем ошибка долетит до экрана.
         */
        const val MAX_RETRIES = 2
    }

    /** `FilmaxImageLoaderFactory` (app) — кэш картинок Coil на диске и в памяти. */
    object ImageCache {
        /** Потолок дискового кэша Coil — один кэш на постеры, фоны и фото актёров. */
        const val DISK_CACHE_MAX_SIZE_BYTES = 1024L * 1024 * 1024

        /**
         * Срок жизни картинки в кэше (сек), который приложение само проставляет в
         * `Cache-Control` — kino.watch и TMDB не всегда шлют внятный заголовок сами. Определяет,
         * как часто картинка перекачивается заново на холодном старте, а не берётся с диска.
         */
        const val MAX_AGE_SECONDS = 30L * 24 * 60 * 60

        /**
         * Доля доступной памяти под кэш Coil — намеренно ниже дефолтных 25%: на TV-боксах с
         * маленькой кучей дефолт приводил к OOM при скролле. Меньше значение — больше промахов
         * кэша (повторное декодирование уже виденных постеров) при пролистывании назад, зато
         * меньше риск OOM на слабых устройствах.
         */
        const val MEMORY_CACHE_SIZE_PERCENT = 0.15
    }

    /** `AppWarmup` (app) — фоновая предзагрузка вкладок Библиотеки/Каталога при старте. */
    object Warmup {
        /**
         * Пауза перед стартом прогрева, мс — чтобы не спорить за канал с первым всплеском
         * запросов главного экрана сразу после запуска приложения.
         */
        const val START_DELAY_MS = 3_000L
    }
}
